#!/usr/bin/env python3
"""Builds the Claude Design animation for rendering.
Writes scenes/design/tk-data.js (all words and timings, from content/script.json and the voice timeline),
out/design/ (open out/design/index.html through any local web server to preview; editor overlays are off)."""
import json, re, shutil
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SRC, OUT = ROOT / "scenes/design", ROOT / "out/design"
VENDOR = {"https://unpkg.com/react@18.3.1/umd/react.production.min.js": "vendor/react.production.min.js",
          "https://unpkg.com/react-dom@18.3.1/umd/react-dom.production.min.js": "vendor/react-dom.production.min.js",
          "https://unpkg.com/@babel/standalone@7.29.0/babel.min.js": "vendor/babel.min.js"}

def page(extra):
    html = (SRC / "template.html").read_text(encoding="utf-8")
    tl = json.loads((ROOT / "out/voice/timeline.json").read_text(encoding="utf-8"))
    sc = tl["scenes"]; total = tl["total_seconds"]
    cuts = [0.0] + [round((sc[i]["end"] + sc[i + 1]["start"]) / 2, 3) for i in range(len(sc) - 1)] + [total]
    m = re.search(r"window\.OM_SCENES = '(\[.*?\])';", html)
    scenes = json.loads(m.group(1))
    assert len(scenes) == len(sc), "OM_SCENES and timeline differ in scene count"
    for i, s in enumerate(scenes):
        s["dur"] = round(cuts[i + 1] - cuts[i], 3); s.pop("nat", None)
    html = html.replace(m.group(0), "window.OM_SCENES = '" + json.dumps(scenes, separators=(",", ":")) + "';")
    boot = "<script>window.__resources = " + json.dumps(VENDOR) + ";" + extra + "</script>\n"
    assert html.count('<script src="./support.js"></script>') == 1
    return html.replace('<script src="./support.js"></script>', boot + '<script src="./support.js"></script>')

def main():
    S = json.loads((ROOT / "content/script.json").read_text(encoding="utf-8"))
    tl = json.loads((ROOT / "out/voice/timeline.json").read_text(encoding="utf-8"))
    data = {"script": {"title": S["meta"]["title"], "tracker": S["globals"]["tracker"]["labels"],
                       "scenes": [{"id": s["id"], "name": s["name"], "on_screen": s["on_screen"], "ui": s.get("ui_text", {})} for s in S["scenes"]]},
            "voice": {"total": tl["total_seconds"], "scenes": [{"id": s["id"], "start": s["start"], "end": s["end"], "sentences": s["sentences"]} for s in tl["scenes"]]},
            "logos": json.loads((SRC / "logos.json").read_text(encoding="utf-8"))}
    js = ("// Generated by scripts/build_design.py from content/script.json and the voice timeline. Do not edit by hand.\n"
          "window.TK_DATA = " + json.dumps(data, ensure_ascii=False, separators=(",", ":")) + ";\n")
    (SRC / "tk-data.js").write_text(js, encoding="utf-8")
    if OUT.exists():
        shutil.rmtree(OUT)
    shutil.copytree(SRC, OUT)
    (OUT / "fonts").mkdir(exist_ok=True); (OUT / "assets").mkdir(exist_ok=True)
    for n in ("Regular", "Medium", "SemiBold", "Bold"):
        shutil.copy2(ROOT / f"assets/fonts/Montserrat-{n}.woff2", OUT / "fonts")
    (OUT / "index.html").write_text(page("window.TK_TWEAKS = {motionEditor: false, voiceover: false, camera: 'Cinematic'};"), encoding="utf-8")
    print(f"design built, {len(data['script']['scenes'])} scenes, {data['voice']['total']:.3f}s")

if __name__ == "__main__":
    main()
